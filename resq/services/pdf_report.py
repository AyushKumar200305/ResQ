def _safe(text: object) -> str:
    """Normalize text for built-in core PDF fonts cleanly."""
    raw = (
        str(text)
        .replace("\u2014", "-")
        .replace("\u2013", "-")
        .replace("\u2192", "->")
        .replace("\u2265", ">=")
        .replace("\u2264", "<=")
    )
    return raw.encode("latin-1", "replace").decode("latin-1")


class _ResQPDF(FPDF):
    """Custom styled PDF layout with persistent control-center header and footer."""

    def __init__(self, scenario_title: str) -> None:
        super().__init__()
        self._scenario_title = _safe(scenario_title)
        self.alias_nb_pages()
        self.set_auto_page_break(auto=True, margin=16)

    def header(self) -> None:
        self.set_fill_color(15, 23, 42)
        self.rect(0, 0, 210, 14, style="F")
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(241, 245, 249)
        self.set_xy(12, 4)
        self.cell(
            120,
            6,
            "ResQ - Disaster Evacuation Flow & Bottleneck Analysis Optimizer",
        )
        self.set_font("Helvetica", "", 8)
        self.set_text_color(148, 163, 184)
        self.cell(66, 6, self._scenario_title[:42], align="R")
        self.ln(12)

    def footer(self) -> None:
        self.set_y(-12)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(100, 116, 139)
        self.cell(
            0,
            6,
            f"Generated by ResQ DAA Evacuation Optimizer | Page {self.page_no()}/{{nb}}",
            align="C",
        )


def _add_section_heading(pdf: _ResQPDF, number: int, title: str) -> None:
    if pdf.get_y() > 250:
        pdf.add_page()
    pdf.ln(3)
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(0, 8, _safe(f"{number}. {title}"), new_x="LMARGIN", new_y="NEXT")
    pdf.set_draw_color(51, 65, 85)
    pdf.line(12, pdf.get_y(), 198, pdf.get_y())
    pdf.ln(3)


def _fit_cell_text(pdf: FPDF, text: object, max_width: float) -> str:
    """Truncate text cleanly to fit within a table cell width without overflowing borders."""
    s = _safe(text)
    limit = max(4.0, max_width - 3.0)
    if pdf.get_string_width(s) <= limit:
        return s
    ellipsis = ".."
    while len(s) > 1 and pdf.get_string_width(s + ellipsis) > limit:
        s = s[:-1]
    return s + ellipsis


def _add_table(
    pdf: _ResQPDF,
    headers: list[str],
    rows: list[list[str]],
    col_widths: list[float],
) -> None:
    if pdf.get_y() > 245:
        pdf.add_page()
    pdf.set_fill_color(30, 41, 59)
    pdf.set_text_color(248, 250, 252)
    pdf.set_font("Helvetica", "B", 8)
    for h, w in zip(headers, col_widths):
        pdf.cell(w, 7, _fit_cell_text(pdf, h, w), border=1, fill=True)
    pdf.ln()

    pdf.set_font("Helvetica", "", 8)
    for r_idx, row in enumerate(rows):
        if pdf.get_y() > 265:
            pdf.add_page()
            pdf.set_fill_color(30, 41, 59)
            pdf.set_text_color(248, 250, 252)
            pdf.set_font("Helvetica", "B", 8)
            for h, w in zip(headers, col_widths):
                pdf.cell(w, 7, _fit_cell_text(pdf, h, w), border=1, fill=True)
            pdf.ln()
            pdf.set_font("Helvetica", "", 8)

        fill_rgb = (248, 250, 252) if r_idx % 2 == 0 else (241, 245, 249)
        pdf.set_fill_color(*fill_rgb)
        pdf.set_text_color(15, 23, 42)
        for val, w in zip(row, col_widths):
            pdf.cell(w, 6, _fit_cell_text(pdf, val, w), border=1, fill=True)
        pdf.ln()
    pdf.ln(2)


def _draw_horizontal_bar_chart(
    pdf: _ResQPDF,
    title: str,
    items: list[tuple[str, float, float, tuple[int, int, int], str]],
    max_val: float,
) -> None:
    """Draw a vector horizontal bar chart directly onto the PDF page.

    Each item is (label, value, _unused, rgb_color, value_text).
    """
    needed_height = 14 + len(items) * 8 + 6
    if pdf.get_y() + needed_height > 272:
        pdf.add_page()

    start_x = 12.0
    start_y = pdf.get_y()
    box_w = 186.0
    pdf.set_fill_color(248, 250, 252)
    pdf.set_draw_color(203, 213, 225)
    pdf.rect(start_x, start_y, box_w, needed_height, style="DF")

    pdf.set_xy(start_x + 4, start_y + 3)
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(0, 5, _safe(title))

    bar_x = start_x + 56
    bar_max_w = 92.0
    y_cursor = start_y + 11
    denom = max_val if max_val > 0 else 1.0

    for label, val, _, rgb, val_text in items:
        pdf.set_xy(start_x + 4, y_cursor)
        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(30, 41, 59)
        pdf.cell(50, 6, _safe(label)[:28])

        pdf.set_fill_color(226, 232, 240)
        pdf.rect(bar_x, y_cursor + 1, bar_max_w, 4.2, style="F")

        fill_w = max(0.0, min(bar_max_w, (val / denom) * bar_max_w))
        if fill_w > 0:
            pdf.set_fill_color(*rgb)
            pdf.rect(bar_x, y_cursor + 1, fill_w, 4.2, style="F")

        pdf.set_xy(bar_x + bar_max_w + 3, y_cursor)
        pdf.set_font("Helvetica", "B", 7.5)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(32, 6, _safe(val_text))
        y_cursor += 8

    pdf.set_y(start_y + needed_height + 4)


def generate_pdf_report(
    bundle: FullAnalysisBundle,
    *,
    comparison: AlgorithmComparisonResult | None = None,
    scenario_evaluations: Sequence[ScenarioEvaluation] | None = None,
) -> bytes:
    """Generate a presentation-ready PDF report from real calculated analysis results."""
    net = bundle.network
    d = bundle.dinic_result
    mc = bundle.min_cut
    comp = comparison or compare_dinic_vs_greedy(
        net, greedy_rule=GreedyRule.SHORTEST_HOP, repeats=3, trace=False
    )

    pdf = _ResQPDF(net.name)
    pdf.set_margins(12, 18, 12)
    pdf.add_page()

    # 1. Project Name & Title Banner
    pdf.set_font("Helvetica", "B", 17)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(
        0,
        9,
        "ResQ - Disaster Evacuation Flow and Bottleneck Analysis Optimizer",
        new_x="LMARGIN",
        new_y="NEXT",
    )
    pdf.set_font("Helvetica", "", 9.5)
    pdf.set_text_color(71, 85, 105)
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    pdf.cell(
        0,
        5,
        _safe(f"Operational Evacuation Audit Report | Generated: {ts}"),
        new_x="LMARGIN",
        new_y="NEXT",
    )
    pdf.ln(3)

    # 2. Scenario Details
    _add_section_heading(pdf, 1, "Project & Scenario Details")
    pdf.set_font("Helvetica", "", 9.5)
    pdf.set_text_color(15, 23, 42)
    pdf.multi_cell(
        0,
        5.5,
        _safe(
            f"Scenario Name: {net.name}\n"
            f"Network Identifier: {net.network_id}\n"
            f"Description: {net.description or 'User-configured directed evacuation network.'}"
        ),
    )

    # 3. Network Summary
    _add_section_heading(pdf, 2, "Network Topology Summary")
    _add_table(
        pdf,
        ["Component", "Count / Total", "Notes"],
        [
            ["Affected Areas (Sources)", str(len(net.affected_areas)), f"Total population: {d.total_population:,}"],
            ["Intermediate Junctions", str(len(net.junctions)), "Zero-supply transit vertices"],
            ["Shelters (Destinations)", str(len(net.shelters)), f"Total shelter capacity: {d.total_shelter_capacity:,}"],
            ["Directed Road Corridors", str(len(net.roads)), f"Active capacity sum: {net.total_active_road_capacity:,}"],
        ],
        [56, 40, 90],
    )

    # 4. Maximum-Flow Result + Chart
    _add_section_heading(pdf, 3, "Dinic Maximum-Flow Evacuation Result")
    _add_table(
        pdf,
        ["Metric", "Calculated Value", "Metric", "Calculated Value"],
        [
            ["Maximum Evacuation Flow", f"{d.max_flow:,}", "Evacuation Completion", f"{d.evacuation_rate * 100:.1f}%"],
            ["People Remaining Unallocated", f"{d.unmet_demand:,}", "BFS Level Phases", str(d.bfs_phases)],
            ["Useful Augmentations", str(d.useful_augmentations), "Dinic Execution Time", f"{d.execution_time_ms:.4f} ms"],
        ],
        [52, 41, 52, 41],
    )
    _draw_horizontal_bar_chart(
        pdf,
        "Chart: Population Evacuated vs. Remaining Unallocated",
        [
            ("Evacuated Flow", float(d.max_flow), 0.0, (34, 197, 94), f"{d.max_flow:,} ({d.evacuation_rate * 100:.1f}%)"),
            ("Unallocated Demand", float(d.unmet_demand), 0.0, (239, 68, 68), f"{d.unmet_demand:,}"),
        ],
        max_val=float(max(1, d.total_population)),
    )

    # 5. Minimum-Cut Analysis + Chart
    _add_section_heading(pdf, 4, "Minimum-Cut & Critical Bottleneck Analysis")
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(15, 23, 42)
    pdf.multi_cell(
        0,
        5,
        _safe(
            f"Max-Flow = Min-Cut Theorem Verified: {d.max_flow:,} = {mc.total_cut_capacity:,}. "
            f"Reachable Partition A: {len(mc.reachable_domain_nodes)} domain node(s) | "
            f"Unreachable Partition B: {len(mc.unreachable_domain_nodes)} domain node(s). "
            f"Cut Breakdown - Road Bottlenecks: {mc.road_cut_capacity:,}, "
            f"Shelter Limits: {mc.shelter_cut_capacity:,}, Source Demand Limits: {mc.super_source_cut_capacity:,}."
        ),
    )
    pdf.ln(2)
    if mc.cut_edges:
        cut_rows = [
            [
                e.edge_kind.replace("_", " ").title(),
                e.edge_id,
                f"{e.source_id} -> {e.target_id}",
                f"{e.original_capacity:,}",
                f"{e.flow:,}",
            ]
            for e in mc.cut_edges
        ]
        _add_table(
            pdf,
            ["Category", "Element ID", "Crossing (A -> B)", "Cut Cap", "Flow"],
            cut_rows,
            [38, 34, 58, 28, 28],
        )
    if mc.road_bottlenecks:
        max_rc = max(e.original_capacity for e in mc.road_bottlenecks)
        _draw_horizontal_bar_chart(
            pdf,
            "Chart: Minimum-Cut Bottleneck Road Capacities",
            [
                (
                    f"{e.edge_id} ({e.source_id}->{e.target_id})",
                    float(e.original_capacity),
                    0.0,
                    (239, 68, 68),
                    f"{e.original_capacity:,}",
                )
                for e in mc.road_bottlenecks[:8]
            ],
            max_val=float(max(1, max_rc)),
        )

    # 6. Shelter Utilization + Chart
    _add_section_heading(pdf, 5, "Shelter Utilization")
    cut_shelter_ids = {e.edge_id for e in mc.shelter_capacity_cuts}
    shl_rows = []
    shl_chart_items = []
    for sid, sd in d.shelter_intakes.items():
        pct = (sd.assigned_flow / sd.shelter_capacity * 100.0) if sd.shelter_capacity > 0 else 0.0
        shl_rows.append(
            [
                sid,
                sd.name,
                f"{sd.shelter_capacity:,}",
                f"{sd.assigned_flow:,}",
                f"{sd.remaining_capacity:,}",
                f"{pct:.1f}%",
                "Yes" if sid in cut_shelter_ids else "No",
            ]
        )
        rgb = (239, 68, 68) if sid in cut_shelter_ids else (34, 197, 94)
        shl_chart_items.append((f"{sid} ({sd.name})", pct, 0.0, rgb, f"{pct:.1f}% ({sd.assigned_flow:,})"))

    _add_table(
        pdf,
        ["ID", "Shelter Name", "Capacity", "Assigned", "Available", "Util %", "Cut Limit"],
        shl_rows,
        [20, 48, 24, 24, 24, 22, 24],
    )
    if shl_chart_items:
        _draw_horizontal_bar_chart(
            pdf,
            "Chart: Shelter-Wise Utilization (%)",
            shl_chart_items[:8],
            max_val=100.0,
        )

    # 7. Road Utilization + Chart
    _add_section_heading(pdf, 6, "Road Corridor Utilization")
    cut_road_ids = {e.edge_id for e in mc.road_bottlenecks}
    road_rows = []
    road_chart_items = []
    sorted_roads = sorted(
        d.road_flows.values(),
        key=lambda r: (-r.utilization_ratio, -r.flow, r.road_id),
    )
    for rf in sorted_roads:
        pct = rf.utilization_ratio * 100.0
        status = (
            "Closed"
            if not rf.is_active
            else ("Min-Cut" if rf.road_id in cut_road_ids else ("Saturated" if rf.is_saturated else "Normal"))
        )
        road_rows.append(
            [
                rf.road_id,
                f"{rf.source_id} -> {rf.target_id}",
                f"{rf.original_capacity:,}",
                f"{rf.flow:,}",
                f"{rf.remaining_capacity:,}",
                f"{pct:.1f}%",
                status,
            ]
        )
        rgb = (
            (239, 68, 68)
            if rf.road_id in cut_road_ids
            else ((245, 158, 11) if rf.is_saturated else (56, 189, 248))
        )
        road_chart_items.append(
            (f"{rf.road_id} ({rf.source_id}->{rf.target_id})", pct, 0.0, rgb, f"{pct:.0f}% ({rf.flow:,}/{rf.original_capacity:,})")
        )

    _add_table(
        pdf,
        ["Road ID", "Corridor", "Capacity", "Flow", "Remaining", "Util %", "Status"],
        road_rows,
        [26, 42, 24, 22, 24, 22, 26],
    )
    if road_chart_items:
        _draw_horizontal_bar_chart(
            pdf,
            "Chart: Top Road Corridor Capacity Utilization (%)",
            road_chart_items[:10],
            max_val=100.0,
        )

    # 8. Dinic vs. Greedy Comparison + Chart
    _add_section_heading(pdf, 7, "Dinic vs. Greedy Baseline Comparison")
    _add_table(
        pdf,
        ["Algorithm", "Total Flow", "Optimality Gap", "Execution Time (ms)"],
        [
            ["Dinic's Maximum Flow", f"{comp.dinic_max_flow:,}", "0.0% (Optimal)", f"{comp.dinic_time_ms:.4f}"],
            [
                f"Greedy ({comp.greedy_result.rule})",
                f"{comp.greedy_flow:,}",
                (
                    f"-{comp.flow_difference:,} ({comp.optimality_gap_pct:.1f}%)"
                    if comp.flow_difference > 0
                    else "0 (0.0%)"
                ),
                f"{comp.greedy_time_ms:.4f}",
            ],
        ],
        [62, 36, 46, 42],
    )
    _draw_horizontal_bar_chart(
        pdf,
        "Chart: Dinic vs. Greedy Total Evacuation Flow",
        [
            ("Dinic Optimal", float(comp.dinic_max_flow), 0.0, (34, 197, 94), f"{comp.dinic_max_flow:,}"),
            (f"Greedy ({comp.greedy_result.rule})", float(comp.greedy_flow), 0.0, (245, 158, 11), f"{comp.greedy_flow:,}"),
        ],
        max_val=float(max(1, comp.dinic_max_flow)),
    )
    pdf.set_font("Helvetica", "", 8.5)
    pdf.set_text_color(51, 65, 85)
    pdf.multi_cell(0, 4.8, _safe(f"Algorithmic Note: {comp.rule_explanation}"))
    pdf.ln(2)

    # Optional Scenario Lab Summary if evaluated
    if scenario_evaluations:
        _add_section_heading(pdf, 8, "What-If Scenario Comparison Summary")
        scn_rows = [
            [
                ev.scenario_name,
                f"{ev.bundle.dinic_result.max_flow:,}",
                f"{ev.bundle.dinic_result.unmet_demand:,}",
                f"{ev.bundle.dinic_result.evacuation_rate * 100:.1f}%",
                f"{ev.baseline_delta:+,}",
            ]
            for ev in scenario_evaluations
        ]
        _add_table(
            pdf,
            ["Scenario", "Max Flow", "Unallocated", "Completion", "Delta vs. Base"],
            scn_rows,
            [68, 28, 30, 28, 32],
        )
        lim_num = 9
    else:
        lim_num = 8

    # 10. Limitations & Disclaimer
    _add_section_heading(pdf, lim_num, "Modeling Limitations & Disclaimer")
    pdf.set_font("Helvetica", "", 8.5)
    pdf.set_text_color(51, 65, 85)
    pdf.multi_cell(
        0,
        4.8,
        _safe(
            "1. Static / Hourly Capacity Model: ResQ models evacuation as a single-commodity integer "
            "maximum-flow network where edge weights represent steady corridor capacities. Dynamic "
            "traffic wave congestion, intersection signal timing, and behavioral rerouting are excluded.\n"
            "2. Execution Time Variance: Reported Dinic and Greedy runtimes are measured locally via "
            "high-resolution performance timers and depend on host hardware, Python interpreter load, "
            "and network structure.\n"
            "3. Operational Disclaimer: Results are intended for DAA algorithmic analysis and "
            "strategic evacuation planning support, not real-time autonomous emergency dispatch."
        ),
    )

    return bytes(pdf.output())
